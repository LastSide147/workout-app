import AsyncStorage from '@react-native-async-storage/async-storage';

// Фильтры экрана Статистики (период рейтинга, допуск по возрасту,
// допуск по весу, выбранное упражнение) раньше жили только в React-
// состоянии — при закрытии приложения (или после OTA-обновления, когда
// JS-бандл перезапускается с нуля) всё обнулялось до значений по
// умолчанию, хотя пользователь их специально настраивал. AsyncStorage
// хранится в файловой системе устройства отдельно от JS-бандла,
// поэтому переживает и закрытие приложения, и обновление бандла —
// значит, достаточно один раз сохранить сюда, и значения сами
// переживут оба случая без какого-либо особого кода "на случай
// обновления".
//
// 'v1' в ключе — на случай, если в будущем сама структура сохраняемых
// данных изменится несовместимо (например, поля переименуют или
// уберут) - тогда можно завести ключ 'v2', и старые данные по старому
// ключу просто перестанут читаться, без миграций и без риска мусора в
// новом формате. Более частый случай (допустимые варианты фильтра
// поменялись, а форма хранения — нет) обрабатывается проще, прямо в
// StatisticsScreen.js: там при восстановлении каждое значение
// проверяется на то, что оно всё ещё входит в список действительных
// вариантов, и если нет — используется значение по умолчанию, а не
// сломанное старое.
const STORAGE_KEY = 'statisticsFilters:v1';

export async function loadStatisticsFilters() {
  try {
    const raw = await AsyncStorage.getItem(STORAGE_KEY);
    if (!raw) {
      return null;
    }
    return JSON.parse(raw);
  } catch (error) {
    console.error('Не удалось прочитать сохранённые фильтры статистики:', error);
    return null;
  }
}

export async function saveStatisticsFilters(filters) {
  try {
    await AsyncStorage.setItem(STORAGE_KEY, JSON.stringify(filters));
  } catch (error) {
    console.error('Не удалось сохранить фильтры статистики:', error);
  }
}
